"""ORM entities for pipeline history.

The schema is owned by the SQL migrations in ``migrations/``; these classes only
describe it. Never call ``Base.metadata.create_all()``: a schema change starts
with a new migration, then the matching change here.
"""

from datetime import datetime
from enum import StrEnum

from sqlalchemy import BigInteger, DateTime, Enum, ForeignKey, Index, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    """Base class for all entities.

    Registers every subclass in ``Base.metadata`` and maps ``datetime``
    annotations to ``TIMESTAMPTZ``, so all timestamps must be timezone-aware.
    """

    type_annotation_map = {datetime: DateTime(timezone=True)}


class RunStatus(StrEnum):
    """Lifecycle of a pipeline run: CREATED -> RUNNING -> COMPLETED | FAILED."""

    CREATED = "CREATED"
    RUNNING = "RUNNING"
    FAILED = "FAILED"
    COMPLETED = "COMPLETED"


class Trigger(StrEnum):
    """Who started a run: a user by hand or the monthly scheduler."""

    MANUAL = "MANUAL"
    SCHEDULER = "SCHEDULER"


class StepType(StrEnum):
    """Pipeline steps, in execution order."""

    INGEST = "INGEST"
    ANALYZE_RAW = "ANALYZE_RAW"
    PROCESS = "PROCESS"
    ANALYZE_FEATURES = "ANALYZE_FEATURES"
    TRAIN = "TRAIN"


class StepStatus(StrEnum):
    """Lifecycle of a step: PENDING -> RUNNING -> COMPLETED | FAILED.

    SKIPPED means the step never ran because an earlier step failed.
    """

    PENDING = "PENDING"
    RUNNING = "RUNNING"
    FAILED = "FAILED"
    COMPLETED = "COMPLETED"
    SKIPPED = "SKIPPED"


def _enum_column(enum: type[StrEnum]) -> Enum:
    """Store an enum as VARCHAR; the CHECK constraint lives in the migration."""
    return Enum(enum, native_enum=False, create_constraint=False, length=20)


class PipelineRun(Base):
    """One execution of the whole pipeline.

    Steps: ingest -> analyze raw -> process -> analyze features -> train.

    A run is the unit of history shown in the app. It is started either by a user
    or by the scheduler when a new monthly dataset is published, and owns one
    ``PipelineStep`` per step type.

    Attributes:
        id: Primary key, generated by the database.
        status: Overall state; FAILED as soon as any step fails.
        trigger: Whether the run was started manually or by the scheduler.
        window_months: Requested length of the trip data window, in months.
        created_at: When the run record was created (set by the database).
        updated_at: Last modification of the record (refreshed on every UPDATE).
        started_at: When the first step began; None while CREATED.
        completed_at: When the run finished, successfully or not.
        steps: Steps of this run. Not loaded lazily: request them explicitly
            with ``selectinload(PipelineRun.steps)`` in the query.
    """

    __tablename__ = "pipeline_run"
    __mapper_args__ = {"eager_defaults": True}

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    status: Mapped[RunStatus] = mapped_column(
        _enum_column(RunStatus), server_default=RunStatus.CREATED.value
    )
    trigger: Mapped[Trigger] = mapped_column(_enum_column(Trigger))
    window_months: Mapped[int]
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())
    started_at: Mapped[datetime | None]
    completed_at: Mapped[datetime | None]

    steps: Mapped[list["PipelineStep"]] = relationship(
        back_populates="run",
        cascade="all, delete-orphan",
        passive_deletes=True,  # the database deletes steps via ON DELETE CASCADE
        lazy="raise_on_sql",
        order_by="PipelineStep.id",
    )

    def __repr__(self) -> str:
        return f"PipelineRun(id={self.id}, status={self.status}, trigger={self.trigger})"


class PipelineStep(Base):
    """One step of a run, with its result stored as JSON.

    Each step type has its own payload in ``step_data`` (downloaded dataset keys
    and the actual period they cover for INGEST, dataset statistics for
    ANALYZE_RAW, train-ready dataset key for PROCESS, feature statistics for
    ANALYZE_FEATURES, model artifact key and metrics for TRAIN). The payload
    structure is defined and validated by the step's Pydantic model, not by the
    database. Large data (tables, models)
    is kept in file storage; ``step_data`` holds only the keys to it.

    A run has at most one step of each type (``UNIQUE (run_id, step_type)``).

    Attributes:
        id: Primary key, generated by the database.
        run_id: Owning run; deleting the run deletes its steps.
        step_type: Which pipeline step this is.
        status: Step state; PENDING until the orchestrator starts it.
        started_at: When the step began.
        completed_at: When the step finished, successfully or not.
        error_message: Why the step failed; None unless status is FAILED.
        step_data: Step result as JSON. Assign a new dict instead of mutating it
            in place, otherwise the change is not saved.
        run: The owning run. Not loaded lazily, see ``PipelineRun.steps``.
    """

    __tablename__ = "pipeline_step"
    __table_args__ = (
        UniqueConstraint("run_id", "step_type"),
        Index("idx_pipeline_step_run_id", "run_id"),
    )
    __mapper_args__ = {"eager_defaults": True}

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    run_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("pipeline_run.id", ondelete="CASCADE")
    )
    step_type: Mapped[StepType] = mapped_column(_enum_column(StepType))
    status: Mapped[StepStatus] = mapped_column(
        _enum_column(StepStatus), server_default=StepStatus.PENDING.value
    )
    started_at: Mapped[datetime | None]
    completed_at: Mapped[datetime | None]
    error_message: Mapped[str | None] = mapped_column(Text)
    step_data: Mapped[dict | None] = mapped_column(JSONB)

    run: Mapped[PipelineRun] = relationship(back_populates="steps", lazy="raise_on_sql")

    def __repr__(self) -> str:
        return f"PipelineStep(id={self.id}, type={self.step_type}, status={self.status})"
